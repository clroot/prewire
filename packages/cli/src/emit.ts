import { posix, relative, resolve, sep } from 'node:path'
import type { ResolvedConfig } from './config'
import type { DiagnosticBag } from './diagnostics'
import type { ResolvedRoot } from './graph'
import { describeToken, tokenId } from './scan'
import type { BindingDecl, TokenId, TokenRef } from './scan'

const upperFirst = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1)
const lowerFirst = (s: string): string => s.charAt(0).toLowerCase() + s.slice(1)

/**
 * Derives the generated export identifier from a token's declared name:
 * SCREAMING_SNAKE becomes lowerCamel (ROUTER → router, PAYMENT_GATEWAY →
 * paymentGateway); anything else gets its first letter lowered. A
 * specialized token is prefixed with its qualifier's type names
 * (REPOSITORY.of<Repository<User>>() → userRepository).
 */
export function deriveExportName(tokenName: string, qualifierParts: string[] = []): string {
  const base = /^[A-Z][A-Z0-9_]*$/.test(tokenName)
    ? tokenName
        .toLowerCase()
        .split('_')
        .filter(Boolean)
        .map((p, i) => (i === 0 ? p : upperFirst(p)))
        .join('')
    : lowerFirst(tokenName)
  if (qualifierParts.length === 0) return base
  return lowerFirst(qualifierParts.map(upperFirst).join('')) + upperFirst(base)
}

function toPosix(p: string): string {
  return p.split(sep).join(posix.sep)
}

function importPath(fromDir: string, toFile: string): string {
  const rel = toPosix(relative(fromDir, toFile)).replace(/\.(ts|tsx)$/, '')
  return rel.startsWith('.') ? rel : `./${rel}`
}

/** Renders one `container.<env>.gen.ts` composition root. */
export function emitRoot(
  root: ResolvedRoot,
  config: ResolvedConfig,
  diagnostics: DiagnosticBag,
): string | undefined {
  const outDirAbs = resolve(config.rootDir, config.outDir)

  // Generated export name per token, with collision detection.
  const exportNames = new Map<TokenId, string>()
  const seenNames = new Map<string, TokenRef>()
  for (const binding of root.bindings) {
    const id = tokenId(binding.provides)
    const name = deriveExportName(binding.provides.name, binding.provides.qualifier?.nameParts)
    const holder = seenNames.get(name)
    if (holder && tokenId(holder) !== id) {
      diagnostics.add(
        'EXPORT_NAME_COLLISION',
        `Tokens ${describeToken(holder)} and ${describeToken(binding.provides)} both derive the generated export name "${name}" — rename one token or type`,
      )
      continue
    }
    seenNames.set(name, binding.provides)
    exportNames.set(id, name)
  }
  if (diagnostics.hasErrors) return undefined

  // Import each winning binding under a collision-free local alias.
  const aliases = new Map<BindingDecl, string>()
  const usedAliases = new Set<string>()
  for (const binding of root.bindings) {
    let alias = `${binding.exportName}Binding`
    let n = 2
    while (usedAliases.has(alias)) alias = `${binding.exportName}Binding${n++}`
    usedAliases.add(alias)
    aliases.set(binding, alias)
  }

  const imports = root.bindings.map(
    (b) =>
      `import { ${b.exportName} as ${aliases.get(b)} } from '${importPath(outDirAbs, b.file)}'`,
  )

  const instances = root.bindings.map((binding) => {
    const name = exportNames.get(tokenId(binding.provides))!
    const args = Object.entries(binding.deps).map(([depName, depRef]) => {
      const depExport = exportNames.get(tokenId(depRef))!
      return depName === depExport ? depName : `${depName}: ${depExport}`
    })
    const depsArg = args.length === 0 ? '{}' : `{ ${args.join(', ')} }`
    return `export const ${name} = /* @__PURE__ */ ${aliases.get(binding)}.factory(${depsArg})`
  })

  const appLabel = config.app ? ` · app "${config.app}"` : ''
  return [
    `/* AUTO-GENERATED by prewire codegen — DO NOT EDIT BY HAND.`,
    ` * Composition root for environment "${root.environment}"${appLabel}.`,
    ` * This is plain wiring code: read it, or eject by copying it into`,
    ` * your source tree and removing the codegen step.`,
    ` */`,
    ...imports,
    '',
    ...instances,
    '',
  ].join('\n')
}

function rootFileName(environment: string): string {
  return `container.${environment}.gen.ts`
}

/**
 * Plans every generated artifact as path → content:
 * - one composition root per environment (environment axis),
 * - `prewire.paths.gen.json` for the app tsconfig / bundler alias
 *   (business-app axis — export conditions cannot vary per importing
 *   app, so resolution is generated per app),
 * - `prewire.manifest.gen.json` consumed by `prewireResolve({ env })`.
 */
export function planOutputs(
  config: ResolvedConfig,
  roots: ResolvedRoot[],
  diagnostics: DiagnosticBag,
): Map<string, string> | undefined {
  const outputs = new Map<string, string>()
  const outDirAbs = resolve(config.rootDir, config.outDir)

  for (const root of roots) {
    const text = emitRoot(root, config, diagnostics)
    if (text === undefined) return undefined
    outputs.set(resolve(outDirAbs, rootFileName(root.environment)), text)
  }

  const rootRelFromConfig = (environment: string): string => {
    const rel = toPosix(relative(config.rootDir, resolve(outDirAbs, rootFileName(environment))))
    return rel.startsWith('.') ? rel : `./${rel}`
  }

  const manifest = {
    specifier: config.specifier,
    ...(config.app !== undefined && { app: config.app }),
    defaultEnvironment: config.defaultEnvironment,
    roots: Object.fromEntries(config.environments.map((env) => [env, rootRelFromConfig(env)])),
  }
  outputs.set(
    resolve(config.rootDir, 'prewire.manifest.gen.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
  )

  if (config.tsconfigPaths) {
    const paths = {
      compilerOptions: {
        paths: { [config.specifier]: [rootRelFromConfig(config.defaultEnvironment)] },
      },
    }
    outputs.set(
      resolve(config.rootDir, 'prewire.paths.gen.json'),
      `${JSON.stringify(paths, null, 2)}\n`,
    )
  }

  return outputs
}

/**
 * Computes the updated app package.json text wiring the environment axis
 * through Node import conditions (`imports` field), keeping `default`
 * last so it stays the fallback condition.
 */
export function planPackageJsonImports(
  config: ResolvedConfig,
  packageJsonText: string,
): string | undefined {
  if (!config.conditions) return undefined
  const pkg = JSON.parse(packageJsonText) as Record<string, unknown>
  const outDirAbs = resolve(config.rootDir, config.outDir)

  const entries: [string, string][] = []
  for (const env of config.environments) {
    const condition = config.conditions[env]
    if (!condition) continue
    const rel = toPosix(relative(config.rootDir, resolve(outDirAbs, rootFileName(env))))
    entries.push([condition, rel.startsWith('.') ? rel : `./${rel}`])
  }
  entries.sort((a, b) => Number(a[0] === 'default') - Number(b[0] === 'default'))

  const imports = (pkg['imports'] as Record<string, unknown> | undefined) ?? {}
  imports[config.specifier] = Object.fromEntries(entries)
  pkg['imports'] = imports
  return `${JSON.stringify(pkg, null, 2)}\n`
}
